#!/usr/bin/env node
/**
 * Dump every on-screen string to markdown (stdout), grouped like the review document:
 * Title and menus, HUD and sheet map, Track I introduction, Event banners, Plain-language hints,
 * Symbols and artefacts, The eight tracks.
 *
 *   node tools/export-text.mjs > docs/on-screen-text.md
 *
 * The text lives in src/text.js (UI) and src/world/levels/*.js (per-track hints, notes, labels).
 */
import { TITLE, SELECT, PAUSE, NOTES, COMPLETE, HUD, MAP, INTRO, BANNER, HINT, CONDITION_TAG, PHASE_WORD,
  TYPE_LABEL, SHORT_LABEL, ARTEFACT_NAMES, TYPE_ROLE, TYPE_NOUN, ROMAN } from '../src/text.js';
import { POI_TYPES } from '../src/world/codes.js';
import { LEVELS } from '../src/world/levels/index.js';
import { buildWorld } from '../src/world/terrain.js';

const esc = (s) => String(s).replace(/\|/g, '\\|');
const out = [];
const line = (s = '') => out.push(s);
function table(head, rows) {
  line(`| ${head.join(' | ')} |`);
  line(`|${head.map(() => '---').join('|')}|`);
  for (const r of rows) line(`| ${r.map(esc).join(' | ')} |`);
  line();
}

line('# CONTOURS: on-screen text');
line();
line('Generated by `node tools/export-text.mjs` from `src/text.js` and `src/world/levels/*.js`. Words in {curly braces} are filled in by the game.');
line();

// ---------------------------------------------------------------- title and menus
line('## Title and menus');
line();
table(['Screen', 'Element', 'Text'], [
  ['Title', 'Cover masthead', TITLE.masthead],
  ['Title', 'Prompt (blinks)', TITLE.prompt],
  ['Title', 'Prompt (touch screens)', TITLE.promptTouch],
  ['Title', 'Controls (keyboard)', TITLE.controlsKeys],
  ['Title', 'Controls (touch)', TITLE.controlsTouch],
  ['Tracklist', 'Header', SELECT.header],
  ['Tracklist', 'Header, right', SELECT.headerRight],
  ['Tracklist', 'Locked track', SELECT.locked],
  ['Tracklist', 'Side panel heading', SELECT.chainHeading],
  ['Tracklist', 'Side panel status', SELECT.statusOpen],
  ['Tracklist', 'Side panel status (walked)', SELECT.statusDone],
  ['Tracklist', 'Side panel prompt', SELECT.prompt],
  ['Tracklist', 'Footer', SELECT.footer],
  ['Pause', 'Heading', PAUSE.heading],
  ...PAUSE.items.map((it) => ['Pause', 'Menu item', it.label]),
  ['Pause', 'Footer', PAUSE.footer],
  ['Field notes', 'Heading', NOTES.heading],
  ['Field notes', 'Count', NOTES.count],
  ['Field notes', 'Empty state', NOTES.empty],
  ['Field notes', 'Footer', NOTES.footer],
  ['Track complete', 'Banner', COMPLETE.banner],
  ['Track complete', 'Line', COMPLETE.line],
  ['Track complete', 'Motif counter', COMPLETE.motifCounter],
  ['Track complete', 'Motif counter', COMPLETE.motifDone],
  ['Track complete', 'Next heading', COMPLETE.nextHeading],
  ['Track complete', 'Last track', COMPLETE.lastTrack],
  ['Track complete', 'Prompt (blinks)', COMPLETE.prompt],
]);

// ---------------------------------------------------------------- HUD and sheet map
line('## HUD and sheet map');
line();
table(['Where', 'Element', 'Text'], [
  ['Top strip', 'Level and track', '{LEVEL NAME} {subtitle}'],
  ['Top strip', 'Altitude', HUD.altitude],
  ['Key bar', 'Gate item', HUD.gate],
  ['Key bar', 'Gate opened', HUD.gateOpen],
  ['Key bar', 'Arrived at target', HUD.here],
  ['Key bar', 'Distance', HUD.km],
  ['Key bar', 'Seconds left while sounding', HUD.seconds],
  ['Resting panel', 'Label', HUD.resting],
  ['Resting panel', 'Time speed', HUD.timeSpeed],
  ['Touch buttons', 'Run / rest', `${HUD.touchRun} · ${HUD.touchRest}`],
  ['Touch stick hint', 'Idle', HUD.touchStick],
  ['Sheet map', 'Legend heading', MAP.legend],
  ['Sheet map', 'Bothy legend row, right', MAP.bothyRow],
  ['Sheet map', 'Key heading', MAP.keyHeading],
  ['Sheet map', 'Several of a type', MAP.anyType],
  ['Sheet map', 'Gate line', MAP.gateLine],
  ['Sheet map', 'Gate opened', MAP.gateOpen],
  ['Sheet map', 'Learned heading', MAP.learned],
  ['Sheet map', 'Learned empty', MAP.learnedEmpty],
  ['Sheet map', 'Route legend', MAP.route],
  ['Sheet map', 'Player position', MAP.you],
  ['Sheet map', 'Scale bar', MAP.scaleBar],
  ['Sheet map', 'Footer', MAP.footer],
]);
line('Condition tags on the sheet map:');
line();
table(['Condition', 'Tag'], [
  ['Come down to it', CONDITION_TAG.descending],
  ['Climb up to it', CONDITION_TAG.ascending],
  ['Approach slowly', CONDITION_TAG.slow],
  ['Arrive at a run', CONDITION_TAG.fast],
  ['Stand still beside it', CONDITION_TAG.dwell],
  ['Unbroken climb', CONDITION_TAG.climb],
  ['At a time of day', Object.values(CONDITION_TAG.time).join(' · ')],
  ['Needs another key sounding', CONDITION_TAG.requires],
]);

// ---------------------------------------------------------------- intro
line('## Track I introduction');
line();
table(['#', 'Text'], INTRO.map((t, i) => [i + 1, t]));

// ---------------------------------------------------------------- banners
line('## Event banners');
line();
table(['When', 'Title', 'Sub-line'], [
  ['A track starts', BANNER.levelStart.title, BANNER.levelStart.sub],
  ['A place wakes and it is part of the key', BANNER.keyWoken.title, BANNER.keyWoken.sub],
  ['A place wakes but is not part of the key', BANNER.notKey.title, BANNER.notKey.sub],
  ['A wrong approach (partial)', BANNER.partial.title, '{poetic hint for that place}; second line: {plain instruction}'],
  ['Two or more artefacts sounding together', BANNER.together.title, BANNER.together.sub],
  ['Coming near a bothy you have not visited', BANNER.bothyNear, ''],
  ['Arriving at a track (first note) or visiting a bothy', BANNER.fieldNote, ''],
  ['Visiting a bothy (guidance)', BANNER.fieldNote.replace('{note}', BANNER.bothyGuide), ''],
  ['Coming near the bealach while it is closed', BANNER.gateStone.title, BANNER.gateStone.sub],
  ['The whole key sounds at once', BANNER.gateUnlocks.title, BANNER.gateUnlocks.sub],
  ['Coming near the bealach once open', BANNER.gateOpen, ''],
]);

// ---------------------------------------------------------------- hints
line('## Plain-language hints');
line();
table(['Condition', 'Text'], [
  ['Come down to it', HINT.descending],
  ['Climb up to it', HINT.ascending],
  ['Approach slowly', HINT.slow],
  ['Arrive at a run', HINT.fast],
  ['Stand still', HINT.dwell],
  ['Unbroken climb (one)', HINT.climbOne],
  ['Unbroken climb (more)', HINT.climbMany],
  ['Time of day', `${HINT.time}  (${Object.entries(PHASE_WORD).map(([k, v]) => `${k}: ${v}`).join(', ')})`],
  ['Needs another key', HINT.requires],
  ['Fallback (should not appear)', HINT.fallback],
]);

// ---------------------------------------------------------------- symbols
line('## Symbols and artefacts');
line();
table(['Place', 'Map label', 'Short label', 'Artefact name', 'Noun in sentences', 'Role line'],
  POI_TYPES.map((t) => [t, TYPE_LABEL[t], SHORT_LABEL[t], ARTEFACT_NAMES[t], TYPE_NOUN[t], TYPE_ROLE[t]]));

// ---------------------------------------------------------------- tracks
function approach(c = {}) {
  const a = [];
  if (c.time) a.push(c.time === 'night' ? 'at night' : `at ${c.time}`);
  if (c.approach === 'descending') a.push('from above');
  if (c.approach === 'ascending') a.push('from below');
  if (c.speed === 'slow') a.push('slowly');
  if (c.speed === 'fast') a.push('at a run');
  if (c.climb) a.push(`climb ${c.climb}`);
  if (c.dwell) a.push(`wait ${c.dwell} s`);
  if (c.requires) a.push(`after the ${c.requires}`);
  return a.length ? a.join(', ') : 'any';
}
line('## The eight tracks');
line();
LEVELS.forEach((lv, i) => {
  const world = buildWorld(lv);
  line(`### ${ROMAN[i]}. ${lv.name}`);
  line();
  line(`Gaelic: ${lv.gaelic} · Subtitle: ${lv.subtitle} · Grid: ${lv.gridLetters} · Bealach: ${lv.gate.name} · Key: ${lv.gate.chain.join(' + ')}`);
  line();
  table(['Place', 'Type', 'Approach', 'Hint'], lv.pois.map((p) => [p.name, p.type, approach(p.condition), p.hint]));
  line('Field notes:');
  line();
  lv.fieldNotes.forEach((n, k) => line(`${k + 1}. ${n}`));
  line();
  line(`Map labels: ${[...new Set(world.features.labels.map((l) => l.text))].join(' · ')}`);
  line();
});

process.stdout.write(out.join('\n') + '\n');

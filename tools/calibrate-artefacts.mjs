#!/usr/bin/env node
// Measures the unity-gain loudness of each artefact's first six seconds, per level (artefact alone, bed muted), and
// writes src/audio/artcal.js. Artefacts.play() aims the entry from it; its servo trims the rest.
//   node tools/calibrate-artefacts.mjs [--level id[,id]] [--parallel N]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import { execSync } from 'node:child_process';
import { startServer } from './lib/serve.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const argv = process.argv.slice(2);
const val = (n) => { const i = argv.indexOf(n); return i >= 0 ? argv[i + 1] : null; };
const IDS = ['corryvreckan', 'cruachan', 'lyon', 'rannoch', 'cairngorm', 'coe', 'cuillin', 'nevis'];
const TYPES = ['trig', 'cairn', 'lochan', 'waterfall', 'bothy', 'stone', 'crag', 'summit'];
const levels = val('--level') ? val('--level').split(',') : IDS;
const file = path.join(root, 'src/audio/artcal.js');

async function loadPlaywright() {
  try { return await import('playwright'); } catch (e) { /* fall through */ }
  const g = execSync('npm root -g').toString().trim();
  return createRequire(path.join(g, 'playwright', 'package.json'))(path.join(g, 'playwright'));
}
function findChromium() {
  const base = '/opt/pw-browsers';
  if (!fs.existsSync(base)) return undefined;
  for (const d of fs.readdirSync(base).filter((x) => x.startsWith('chromium-'))) {
    const p = path.join(base, d, 'chrome-linux', 'chrome');
    if (fs.existsSync(p)) return p;
  }
  return undefined;
}

// existing table (partial runs merge into it)
let table = {};
try { const m = fs.readFileSync(file, 'utf8').match(/ART_NOMINAL = (\{[\s\S]*?\});\n/); if (m) table = JSON.parse(m[1]); } catch (e) { /* none yet */ }

const { url, close } = await startServer(root, 0, {});
const pw = await loadPlaywright();
const exe = findChromium();
const browser = await (pw.chromium || pw.default.chromium).launch({ ...(exe ? { executablePath: exe } : {}), headless: true, args: ['--autoplay-policy=no-user-gesture-required', '--no-sandbox'] });
const n = Math.max(1, Math.min(levels.length, Number(val('--parallel') || 4)));
const pages = [];
for (let i = 0; i < n; i++) {
  const pg = await browser.newPage();
  pg.on('pageerror', (e) => console.log('pageerror', e.message));
  await pg.goto(url + '/tools/lib/audio-page.html');
  await pg.waitForFunction('window.__ready === true', null, { timeout: 60000 });
  pages.push(pg);
}
let next = 0;
await Promise.all(pages.map(async (pg) => {
  while (next < levels.length) {
    const id = levels[next++];
    const r = await pg.evaluate(([i, t]) => window.calibrateArtefacts(i, t), [id, TYPES]);
    table[id] = r;
    console.log(id.padEnd(10) + TYPES.map((t) => (r[t] + '/' + r[t + '@late']).padStart(12)).join(''));
  }
}));
const sorted = {};
for (const id of IDS) if (table[id]) sorted[id] = table[id];
fs.writeFileSync(file, `// Generated by tools/calibrate-artefacts.mjs: RMS (dBFS) of each artefact's first six seconds, played alone at unity.\n// Artefacts.play() aims the entry from this; re-run the tool after changing a piece, a voice or a channel.\nexport const ART_NOMINAL = ${JSON.stringify(sorted)};\n`);
console.log('wrote src/audio/artcal.js');
await browser.close(); await close();

/**
 * Baked-image codec (ENCODER; the decoder is src/render/title/bakedkit.js so the browser needs nothing from tools/).
 *
 * encodeSymbols(Uint8Array) -> base64 string. Bytes before base64:
 *   [mode, nsym, sym0 .. sym(nsym-1), body...]
 *   mode 0  bit-packed: each pixel is its index into the symbol table, bpp = ceil(log2 nsym) bits, LSB first (nsym 1 => empty body)
 *   mode 1  RLE (nsym <= 16): token = (symIndex << 4) | c ; c 0..14 => run c+1, c 15 => the next byte b gives run 16+b (16..271)
 * the encoder emits whichever is smaller. Dithered greys pack at 3 bits/pixel (~31 KB for 384x216); flat areas (layer hints) RLE to a few KB.
 */
export function encodeSymbols(data) {
  const seen = new Map(), table = [];
  for (const v of data) if (!seen.has(v)) { seen.set(v, table.length); table.push(v); }
  const nsym = table.length;
  // mode 0
  const bpp = nsym <= 1 ? 0 : Math.ceil(Math.log2(nsym));
  const body0 = new Uint8Array(Math.ceil(data.length * bpp / 8));
  if (bpp) {
    let bit = 0;
    for (let i = 0; i < data.length; i++) {
      const s = seen.get(data[i]);
      for (let b = 0; b < bpp; b++, bit++) if ((s >> b) & 1) body0[bit >> 3] |= 1 << (bit & 7);
    }
  }
  let best = { mode: 0, body: body0 };
  if (nsym <= 16) {
    const out = [];
    let i = 0;
    while (i < data.length) {
      let j = i; while (j < data.length && data[j] === data[i] && j - i < 271) j++;
      const run = j - i, s = seen.get(data[i]);
      if (run <= 15) out.push((s << 4) | (run - 1)); else out.push((s << 4) | 15, run - 16);
      i = j;
    }
    if (out.length < body0.length) best = { mode: 1, body: Uint8Array.from(out) };
  }
  const head = Uint8Array.from([best.mode, nsym & 255, ...table]);
  return Buffer.from(Uint8Array.from([...head, ...best.body])).toString('base64');
}

export function fnv1a(buf) { let h = 0x811c9dc5; for (let i = 0; i < buf.length; i++) { h ^= buf[i]; h = Math.imul(h, 0x01000193) >>> 0; } return h.toString(16).padStart(8, '0'); }

/** { w, h, idx(Uint8Array palette indices), layer(Uint8Array), accent?(Uint8Array mask of accent pixels), emberIdx?, meta } -> JS module source.
 *  The accent list ("embers") is the mask's pixels when a mask is given (the blue accent: frost / paleblue are also ordinary ramp colours, so the colour alone
 *  cannot tell), else every pixel equal to emberIdx (the old red ember). */
export function bakedModuleSource({ w, h, idx, layer, accent, emberIdx, meta }) {
  const embers = [];
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) if (accent ? accent[y * w + x] : idx[y * w + x] === emberIdx) embers.push([x, y, (x + 2 * y) % 16]);
  const obj = { w, h, idx: encodeSymbols(idx), layer: encodeSymbols(layer), embers: '@@E@@', meta };
  const json = JSON.stringify(obj, null, 1).replace('"@@E@@"', '[' + embers.map((e) => '[' + e.join(',') + ']').join(',') + ']');
  return { source: `// GENERATED by tools/bake-title.mjs -- do not edit. Scene "${meta.scene}", ${w}x${h}, accent pixels ${embers.length}.\n// Consume with decodeBaked / blitBaked / pulseBakedEmbers from src/render/title/bakedkit.js\nexport default ${json};\n`, embers };
}
